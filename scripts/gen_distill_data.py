"""Generate V14 distillation data from the ported teacher (mem-safe).

Teacher = ported Qwen2.5-Coder-3B (GLA+MoE8) under torchao load-time int4
(5.3GB VRAM, ~60 tok/s). It answers coding prompts; the V14 student then
SFTs on {prompt, response} — no vocab alignment needed (CE on teacher
text, not KD on teacher logits: vocab 151936 vs 65536 makes logit-KD
impractical anyway).

Sources of prompts:
  - data/sft/pie_sft.jsonl      (3000 "rewrite faster" prompts)
  - data/sft/evolve_sft.jsonl   (61 real evolve prompts)

Usage:
    python scripts/gen_distill_data.py --n 500 --out data/sft/v14_distill.jsonl \
        --ckpt research/checkpoints/qwen25_coder_3b_mla_moe
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
import contextlib

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default="research/checkpoints/qwen25_coder_3b_mla_moe")
    ap.add_argument("--data", nargs="+",
                    default=["data/sft/pie_sft.jsonl", "data/sft/evolve_sft.jsonl"])
    ap.add_argument("--n", type=int, default=500)
    ap.add_argument("--max-new", type=int, default=384)
    ap.add_argument("--out", default="data/sft/v14_distill.jsonl")
    ap.add_argument("--skip-existing", action="store_true",
                    help="resume: skip prompts already present in --out")
    args = ap.parse_args()

    # Collect unique prompts (cap per row: prompt field only, response is
    # regenerated by the teacher so the student learns teacher style).
    prompts: list[str] = []
    seen: set[str] = set()
    for dp in args.data:
        p = Path(dp)
        if not p.exists():
            continue
        for line in p.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            pr = row.get("prompt")
            if pr and pr not in seen:
                seen.add(pr)
                prompts.append(pr)
    print(f"[distill] {len(prompts)} unique prompts", flush=True)

    done_prompts: set[str] = set()
    out_p = Path(args.out)
    if args.skip_existing and out_p.exists():
        for line in out_p.read_text(encoding="utf-8").splitlines():
            with contextlib.suppress(json.JSONDecodeError):
                done_prompts.add(json.loads(line).get("prompt", ""))
        print(f"[distill] resume: {len(done_prompts)} done", flush=True)

    from forge.engine.forge_engine import ForgeEngine
    eng = ForgeEngine.from_checkpoint(
        args.ckpt, load_quantize="int4", use_adaptive_spec=False)

    n_written = 0
    t0 = time.time()
    with out_p.open("a", encoding="utf-8") as f:
        for i, pr in enumerate(prompts):
            if n_written >= args.n:
                break
            if pr in done_prompts:
                continue
            try:
                out = eng.generate(
                    pr, max_new_tokens=args.max_new, temperature=0.7,
                    top_p=0.95, top_k=80, finish_sentence=False,
                    stop=[eng.tokenizer.decode([151645])])
            except Exception as e:
                print(f"[distill] gen failed @{i}: {e}", flush=True)
                continue
            text = out if isinstance(out, str) else out.get("text", "")
            if len(text.strip()) < 20:
                continue
            f.write(json.dumps({"prompt": pr, "response": text}) + "\n")
            f.flush()
            n_written += 1
            if n_written % 10 == 0:
                rate = n_written / (time.time() - t0)
                print(f"[distill] {n_written}/{args.n} "
                      f"({rate:.2f} rows/s)", flush=True)
    print(f"[distill] wrote {n_written} rows -> {out_p} "
          f"in {time.time() - t0:.0f}s", flush=True)


if __name__ == "__main__":
    main()
