"""Regenerate scripts/README.md — the categorized index of scripts/.

Run after adding/renaming a script:

    venv\\Scripts\\python.exe scripts\\build_script_index.py

Extracts each script's first docstring line, groups by prefix family,
and writes scripts/README.md. `_archive/` is excluded by design.
"""
import ast
import re
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "scripts"

# (header, filename-regex). First match wins — order matters.
GROUPS = [
    ("Benchmarks", r"^bench_"),
    ("Debug harnesses", r"^dbg_"),
    ("Probes & diagnostics", r"^probe_|^overclock_probe|^show_winners"),
    ("EXP experiment surfaces", r"^exp_"),
    ("Port & parity checks", r"^test_|_port\b|parity"),
    ("Smoke tests", r"^smoke_"),
    ("Data download & filtering", r"^download_|^dl_|^fetch_|^filter_|^scrape_"),
    ("Data generation & SFT export", r"^gen_|^generate_|^make_"),
    ("Evolve-loop drivers", r"evolve|rsi_|scout_|ledger_|fn_evolve"),
    ("Training & merging", r"^train_|^finetune|^lora_|^distill|^merge_|^score_|^compare_"),
    ("Model conversion & packing", r"^convert|^port_|^prequant|^assemble|^truncate_|^quant"),
    ("Eval & verification", r"^eval_|^check_|^verify|^rescore|^run_external"),
]

HEADER = """# Scripts Index

Auto-generated by `scripts/build_script_index.py` — rerun it after
adding/renaming scripts. `_archive/` is excluded.

**Prefix conventions for new scripts:** `bench_` benchmarks ·
`dbg_`/`probe_` diagnostics · `exp_` EXP-surface experiments ·
`smoke_` smoke tests · `test_*` port/parity harnesses (NOT pytest —
real tests live in `tests/`) · `download_`/`gen_` data pipelines ·
`*_evolve`/`rsi_` loop drivers · `train_`/`distill`/`merge` training.

"""

FOOTER = """
## Uncategorized

Scripts not matching a prefix family land here — consider renaming to a
conventional prefix when next touched.
"""


def docline(path: Path) -> str:
    try:
        tree = ast.parse(path.read_bytes())
        doc = ast.get_docstring(tree) or ""
        return " ".join(doc.split())[:110] or "(no docstring)"
    except Exception:
        return "(unparseable)"


def main() -> None:
    files = sorted(p for p in SCRIPTS.glob("*.py")
                   if p.name != Path(__file__).name)
    groups: OrderedDict[str, list] = OrderedDict((h, []) for h, _ in GROUPS)
    misc = []
    for p in files:
        name = p.name
        hit = next((h for h, pat in GROUPS if re.search(pat, name)), None)
        (groups[hit] if hit else misc).append((name, docline(p)))

    out = [HEADER]
    for h, rows in groups.items():
        if not rows:
            continue
        out.append(f"## {h} ({len(rows)})\n")
        out.append("| Script | Purpose |")
        out.append("|---|---|")
        for name, doc in rows:
            out.append(f"| `{name}` | {doc} |")
        out.append("")
    if misc:
        out.append(FOOTER)
        for name, doc in misc:
            out.append(f"- `{name}` — {doc}")
        out.append("")

    dest = SCRIPTS / "README.md"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {dest} — {len(files)} scripts, "
          f"{sum(len(r) for r in groups.values())} categorized, "
          f"{len(misc)} uncategorized")


if __name__ == "__main__":
    main()
