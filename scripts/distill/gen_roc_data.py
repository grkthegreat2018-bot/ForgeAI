"""Rocinante teacher -> RP transcript generator.

Runs the Roc GGUF in llama.cpp (GPU) and produces JSONL chat transcripts:
    {"id": ..., "messages": [{"role": "system"|"user"|"assistant", "content": ...}]}

Three generation modes (mixed per config):
  scene    - single rich reply to a scenario card (system+user -> assistant)
  convo    - multi-turn: teacher writes BOTH sides via role-switch prompts
             (best style consistency; user turns are still Roc-voiced)
  continue - freeform story continuation chunked into assistant turns

I author no training text here - the prompt bank below is a mechanical
combinatorial seed grid (genre x setting x archetype x hook). All dataset
content is generated by the local model.

Usage (Forge venv - llama_cpp lives there):
  venv\\Scripts\\python.exe scripts\\distill\\gen_roc_data.py \
      --out data\\roc_distill.jsonl --n-scenes 500 --n-convos 300 \
      --n-cont 100 --max-tokens 700 --gpu-layers -1
"""
from __future__ import annotations

import argparse
import json
import os
import random
import time

# EC-091: no machine-specific paths — pass --gguf or set ROC_GGUF env var.
GGUF = os.environ.get("ROC_GGUF", "")

# ---- mechanical seed grid (no authored prose) -------------------------------
GENRES = ["fantasy", "sci-fi", "modern", "historical", "horror", "noir",
          "post-apocalyptic", "slice-of-life", "mystery", "adventure"]
SETTINGS = {
    "fantasy": ["a borderland tavern", "a crumbling mage tower", "an enchanted forest road", "a besieged citadel"],
    "sci-fi": ["a derelict starship", "an orbital station bar", "a colony on a tidally-locked world", "a smuggler's hideout"],
    "modern": ["a rain-soaked city apartment", "an all-night diner", "a hospital rooftop", "a tour bus at 3am"],
    "historical": ["a Victorian parlour", "a WWI field hospital", "a roman villa", "an edo-period teahouse"],
    "horror": ["an abandoned asylum", "a village that isn't on any map", "a house inherited from a stranger", "a ship adrift in fog"],
    "noir": ["a smoke-filled detective office", "a nightclub back room", "a waterfront warehouse", "a courthouse corridor"],
    "post-apocalyptic": ["a fortified fuel station", "an overgrown shopping mall", "a caravan on a dead highway", "an underground bunker"],
    "slice-of-life": ["a small-town bakery", "a university library", "a neighbourhood bar", "a family-run inn"],
    "mystery": ["a locked country manor", "a night train", "a museum after closing", "a remote research outpost"],
    "adventure": ["an uncharted jungle temple", "a pirate cove", "a mountain expedition camp", "a desert caravan route"],
}
ARCHETYPES = ["a cynical veteran", "an enigmatic stranger", "a cheerful trickster",
              "a brooding noble", "a reluctant hero", "a sharp-tongued scholar",
              "a loyal bodyguard", "a charming rogue", "a haunted exile",
              "an ambitious prodigy", "a weary caretaker", "a dangerous ally"]
HOOKS = ["a tense negotiation", "an unexpected reunion", "a desperate request for help",
         "a discovered secret", "a confrontation long avoided", "a fragile alliance",
         "an escape gone wrong", "a confession at the worst moment",
         "a bargain with hidden terms", "the aftermath of a disaster",
         "a quiet moment before the storm", "a rivalry forced into partnership"]
USER_OPENERS = ["*I approach cautiously.* What is this place?",
                "Who are you? And don't lie to me.",
                "I need your help. Name your price.",
                "*sits down across from you* We need to talk.",
                "You're not supposed to be here.",
                "I've heard stories about you.",
                "Stay back. I mean it.",
                "*offers a hand* Looks like we're stuck together.",
                "Tell me what you know.",
                "You first. I'm right behind you."]
USER_FOLLOWUPS = ["That's not good enough. Try again.",
                  "*crosses arms* And why should I trust you?",
                  "Fine. What do we do now?",
                  "You're hiding something.",
                  "*laughs despite the situation*",
                  "Go on. I'm listening.",
                  "We don't have time for this.",
                  "What aren't you telling me?",
                  "*pauses, then nods slowly*",
                  "That changes things. What's the plan?"]

SYS_TPL = ("You are {arch}. Write vivid, character-driven roleplay responses in "
           "{genre}. Stay in character, show don't tell, and weave dialogue with "
           "action and sensory detail. Setting: {setting}.")

SCENE_TPL = ("Write the opening reply to this roleplay. Your character is {arch}. "
             "The scene begins with {hook} at {setting}. Reply in character with "
             "rich detail, 3-5 paragraphs.")

CONT_TPL = ("Continue this {genre} story set at {setting}, centered on {arch} "
            "facing {hook}. Write the next section, 4-6 paragraphs.")


def mistral_wrap(messages):
    """Render messages into a single Mistral [INST] prompt for raw completion."""
    out = []
    sys = ""
    for m in messages:
        if m["role"] == "system":
            sys += m["content"] + "\n\n"
        elif m["role"] == "user":
            out.append("[INST] " + sys + m["content"].strip() + " [/INST]")
            sys = ""
        else:
            out.append(m["content"].strip() + " </s>")
    return "".join(out)  # llama_cpp adds BOS itself


def _trim_incomplete(text):
    """Cut a length-truncated reply back to the last sentence boundary."""
    import re
    if re.search(r'[.!?…]["\')\]*»]?\s*$', text):
        return text
    m = list(re.finditer(r'[.!?…]["\')\]*»]?', text))
    if not m or m[-1].end() < len(text) * 0.4:
        return None  # nothing clean to keep
    return text[:m[-1].end()].rstrip()


def gen(llm, prompt, max_tokens, temp, stop):
    """llm is either a llama_cpp.Llama or a server URL string."""
    if isinstance(llm, str):
        import urllib.request
        body = json.dumps({"prompt": prompt, "n_predict": max_tokens,
                           "temperature": temp, "top_p": 0.9,
                           "repeat_penalty": 1.05, "stop": stop}).encode()
        req = urllib.request.Request(llm.rstrip("/") + "/completion",
                                     data=body,
                                     headers={"Content-Type": "application/json"})
        r = json.load(urllib.request.urlopen(req))
        text = r["content"].strip()
        if r.get("stopped_limit"):
            text = _trim_incomplete(text) or ""
        return text
    r = llm(prompt, max_tokens=max_tokens, temperature=temp, top_p=0.9,
            repeat_penalty=1.05, stop=stop, echo=False)
    c = r["choices"][0]
    text = c["text"].strip()
    if c.get("finish_reason") == "length":
        text = _trim_incomplete(text) or ""
    return text


def make_scene(llm, rng, max_tokens, temp):
    genre = rng.choice(GENRES)
    setting = rng.choice(SETTINGS[genre])
    arch = rng.choice(ARCHETYPES)
    hook = rng.choice(HOOKS)
    sys_p = SYS_TPL.format(arch=arch, genre=genre, setting=setting)
    user = SCENE_TPL.format(arch=arch, hook=hook, setting=setting)
    prompt = mistral_wrap([{"role": "system", "content": sys_p},
                           {"role": "user", "content": user}])
    text = gen(llm, prompt, max_tokens, temp, stop=["[INST]", "</s>"])
    if len(text) < 200:
        return None
    return {"kind": "scene", "genre": genre,
            "messages": [{"role": "system", "content": sys_p},
                         {"role": "user", "content": user},
                         {"role": "assistant", "content": text}]}


def make_convo(llm, rng, max_tokens, temp, turns):
    genre = rng.choice(GENRES)
    setting = rng.choice(SETTINGS[genre])
    arch = rng.choice(ARCHETYPES)
    hook = rng.choice(HOOKS)
    sys_p = SYS_TPL.format(arch=arch, genre=genre, setting=setting)
    user = (rng.choice(USER_OPENERS)
            + f"\n\n[scene: {hook} at {setting}]")
    msgs = [{"role": "system", "content": sys_p},
            {"role": "user", "content": user}]
    for _t in range(turns):
        prompt = mistral_wrap(msgs)
        reply = gen(llm, prompt, max_tokens, temp, stop=["[INST]", "</s>"])
        if len(reply) < 120:
            break
        msgs.append({"role": "assistant", "content": reply})
        # user turn: teacher voices the user's next message too
        follow = rng.choice(USER_FOLLOWUPS)
        msgs.append({"role": "user", "content": follow})
    if sum(1 for m in msgs if m["role"] == "assistant") < 2:
        return None
    msgs.pop()  # trailing unanswered user turn
    return {"kind": "convo", "genre": genre, "messages": msgs}


def make_continue(llm, rng, max_tokens, temp):
    genre = rng.choice(GENRES)
    setting = rng.choice(SETTINGS[genre])
    arch = rng.choice(ARCHETYPES)
    hook = rng.choice(HOOKS)
    sys_p = SYS_TPL.format(arch=arch, genre=genre, setting=setting)
    user = CONT_TPL.format(genre=genre, setting=setting, arch=arch, hook=hook)
    prompt = mistral_wrap([{"role": "system", "content": sys_p},
                           {"role": "user", "content": user}])
    text = gen(llm, prompt, max_tokens, temp, stop=["[INST]", "</s>"])
    if len(text) < 300:
        return None
    return {"kind": "continue", "genre": genre,
            "messages": [{"role": "system", "content": sys_p},
                         {"role": "user", "content": user},
                         {"role": "assistant", "content": text}]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=r"data\roc_distill.jsonl")
    ap.add_argument("--gguf", default=GGUF,
                    help="Path to the Rocinante GGUF (default: ROC_GGUF env var)")
    ap.add_argument("--n-scenes", type=int, default=500)
    ap.add_argument("--n-convos", type=int, default=300)
    ap.add_argument("--n-cont", type=int, default=100)
    ap.add_argument("--convo-turns", type=int, default=4)
    ap.add_argument("--max-tokens", type=int, default=700)
    ap.add_argument("--temp", type=float, default=0.85)
    ap.add_argument("--ctx", type=int, default=8192)
    ap.add_argument("--gpu-layers", type=int, default=-1)
    ap.add_argument("--server", default=None,
                    help="llama-server base URL, e.g. http://127.0.0.1:8383")
    ap.add_argument("--seed", type=int, default=1234)
    args = ap.parse_args()

    rng = random.Random(args.seed)
    if args.server:
        llm = args.server
    else:
        if not args.gguf:
            ap.error("--gguf or ROC_GGUF env var required (or use --server)")
        from llama_cpp import Llama
        llm = Llama(model_path=args.gguf, n_ctx=args.ctx,
                    n_gpu_layers=args.gpu_layers, verbose=False)

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    plan = (["scene"] * args.n_scenes + ["convo"] * args.n_convos
            + ["continue"] * args.n_cont)
    rng.shuffle(plan)
    made, t0 = 0, time.time()
    with open(args.out, "a", encoding="utf-8") as fh:
        for i, kind in enumerate(plan):
            try:
                rec = (make_scene if kind == "scene"
                       else make_continue if kind == "continue"
                       else lambda l, r, mt, tp: make_convo(l, r, mt, tp, args.convo_turns)
                       )(llm, rng, args.max_tokens, args.temp)
            except Exception as e:
                print(f"[{i}] {kind} failed: {e}", flush=True)
                continue
            if rec is None:
                continue
            rec["id"] = made
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
            fh.flush()
            made += 1
            if made % 25 == 0:
                el = time.time() - t0
                print(f"{made}/{len(plan)} records, {el/60:.1f} min "
                      f"({made/el*60:.1f}/min)", flush=True)
    print(f"done: {made} records -> {args.out}", flush=True)


if __name__ == "__main__":
    main()
